"""Write the Tutorials part of public/docs.html from tutorials.json (the cases
recorded by run_server.py and run_tools.py against a local server).
Run from anywhere: python3 infra/tutorials/build_docs.py. A second run changes nothing."""
import html, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.join(HERE, '../../src/api-gateway-rs/public/docs.html')
E = html.escape
TUTS = json.load(open(os.path.join(HERE, 'tutorials.json')))
DROPPED_NOTE = 'Responses are shortened to the fields that matter (no timestamps or idempotency keys).'

CSS = """  /* tutorials:start (generated by infra/tutorials/build_docs.py) */
  .tut-video { width: 100%; aspect-ratio: 16 / 9; border-radius: 10px; border: 1px solid var(--border-dark); background: #fff; margin: 6px 0 16px; }
  details.case { border: 1px solid var(--border-dark); border-radius: 10px; margin: 10px 0; background: var(--ink-2); }
  details.case > summary { cursor: pointer; padding: 11px 14px; font-weight: 600; list-style: none; display: flex; gap: 10px; align-items: center; }
  details.case > summary::-webkit-details-marker { display: none; }
  details.case > summary::before { content: "+"; width: 14px; color: var(--muted); font-family: 'JetBrains Mono', monospace; }
  details.case[open] > summary::before { content: "-"; }
  details.case > div { padding: 0 14px 4px; }
  details.case pre { margin: 6px 0 12px; }
  .st-code { font-family: 'JetBrains Mono', monospace; font-size: 12px; font-weight: 700; border-radius: 6px; padding: 1px 7px; margin-left: auto; }
  .st-ok { background: rgba(43,127,184,0.14); color: var(--signal); }
  .st-held { background: rgba(217,181,75,0.16); color: var(--dedup); }
  .st-err { background: rgba(192,57,43,0.12); color: #C0392B; }
  .tut-list { columns: 2; padding-left: 18px; }
  @media (max-width: 700px) { .tut-list { columns: 1; } }
  /* tutorials:end */
"""

def st(code):
    cls = 'st-held' if code == 202 else 'st-ok' if code < 300 else 'st-err'
    return f'<span class="st-code {cls}">{code}</span>'

def pre(text):
    return f'<pre><code>{E(text)}</code></pre>'

def curl(c):
    b = c['body']
    h = ''.join(f' \\\n  -H "{k}: {v}"' for k, v in c['headers'].items() if k != 'Authorization')
    auth = c['headers'].get('Authorization', 'Bearer $AGENTRAAS_KEY')
    return (f'curl -X POST "$AGENTRAAS_URL/v1/webhook/org_acme/{c.get("agent", "billing-agent")}" \\\n'
            f'  -H "Authorization: {auth}" -H "Content-Type: application/json"{h} \\\n'
            f"  -d '{json.dumps(b)}'")

def case_html(c):
    if 'cmd' in c:
        out = '\n'.join(l for l in c['output'].splitlines() if not l.startswith('scanning '))
        f = f'<p>{E(c["file"]["name"])}</p>{pre(c["file"]["text"].rstrip())}' if c.get('file') else ''
        code = f'<span class="st-code {"st-ok" if c.get("exit") == 0 else "st-err"}">exit {c.get("exit")}</span>'
        return (f'<details class="case"><summary>{E(c["title"])}{code}</summary><div>'
                f'<p>{E(c["why"])}</p>{f}{pre("$ " + c["cmd"] + chr(10) + out)}</div></details>')
    if 'method' in c:
        req = f'{c["method"]} {c["path"]}' + (f'\n{json.dumps(c["body"])}' if c.get('body') else '') + (f'\n\n# {c["shown"]}' if c.get('shown') else '')
    else:
        req = curl(c)
    return (f'<details class="case"><summary>{E(c["title"])}{st(c["status"])}</summary><div>'
            f'<p>{E(c["why"])}</p>{pre(req)}{pre(json.dumps(c["response"], indent=2))}</div></details>')

def setup_html(t):
    su, out = t['setup'], ['<h3>Set it up</h3>']
    if su.get('install'):
        out.append(pre(su['install']))
    if su.get('dashboard'):
        out.append('<ol>' + ''.join(f'<li>{E(s)}</li>' for s in su['dashboard']) + '</ol>')
    if su.get('api'):
        a = su['api']
        out.append(f'<p>Or with the API (logged in as a member of the org):</p>{pre(a["method"] + " " + a["path"] + chr(10) + json.dumps(a["body"], indent=2))}')
        if su.get('returns'):
            out.append(f'<p>It returns the agent\'s key and URLs:</p>{pre(json.dumps(su["returns"], indent=2))}')
    for r in su.get('rules', []):
        out.append(f'<p>Rule used below: {E(r["label"])}.</p>{pre(r["method"] + " " + r["path"] + chr(10) + json.dumps(r["body"], indent=2))}')
    if su.get('file'):
        out.append(f'<p><code>{E(su["file"]["name"])}</code>:</p>{pre(su["file"]["text"].rstrip())}')
    notes = su.get('notes', []) + su.get('env', [])
    if notes:
        out.append('<ul>' + ''.join(f'<li>{E(n)}</li>' for n in notes) + '</ul>')
    return ''.join(out)

def section(t):
    vid = f'/videos/tutorial-{t["id"]}.mp4'
    return (f'\n    <section id="tut-{t["id"]}">\n      <h2>{E(t["title"])}</h2>\n'
            f'      <p>{E(t["summary"])}</p>\n'
            f'      <video class="tut-video" controls preload="none" poster="/videos/tutorial-{t["id"]}.jpg" src="{vid}"></video>\n'
            f'      {setup_html(t)}\n      <h3>Every case</h3>\n      <p>Click a case to see the request and the real response.</p>\n'
            + ''.join(f'      {case_html(c)}\n' for c in t['cases']) + '    </section>\n')

content = ('<!-- tutorials:start (generated by infra/tutorials/build_docs.py; edit tutorials.json there) -->\n'
           '    <section id="tutorials">\n      <h2>Tutorials</h2>\n'
           '      <p>One feature at a time: how to set it up, then every case you can run into, each with the real request and the real response. '
           'Every example was run against a self-hosted server: <code>$AGENTRAAS_URL</code> is <code>http://localhost:13000</code> there, or <code>https://agentraas.io</code> on Cloud, '
           'and <code>$AGENTRAAS_KEY</code> is the agent\'s key from <b>Connect agent</b>.</p>\n'
           '      <p>The payment examples use <code>mockpay</code>, the built-in sandbox service, so nothing real is charged. It fails about one call in ten at random unless the payload says <code>"fail": false</code>, which is why the examples send it (the Failures tutorial sends <code>"fail": true</code>). '
           + DROPPED_NOTE + '</p>\n'
           '      <h3>The whole loop in two minutes</h3>\n'
           '      <video class="tut-video" controls preload="none" poster="/videos/tutorial-overview.jpg" src="/videos/tutorial-overview.mp4"></video>\n'
           '      <ul class="tut-list">' + ''.join(f'<li><a href="#tut-{t["id"]}">{E(t["title"])}</a></li>' for t in TUTS) + '</ul>\n'
           '    </section>\n' + ''.join(section(t) for t in TUTS) + '    <!-- tutorials:end -->')

nav = ('<!-- tutorials-nav:start -->\n    <div class="group">\n      <div class="group-label">Tutorials</div>\n      <a href="#tutorials">Overview</a>\n'
       + ''.join(f'      <a href="#tut-{t["id"]}">{E(t["title"])}</a>\n' for t in TUTS) + '    </div>\n    <!-- tutorials-nav:end -->')

doc = open(DOCS).read()
before = doc

def put(doc, start, end, new, anchor):
    pat = re.compile(re.escape(start) + r'.*?' + re.escape(end), re.S)
    if pat.search(doc):
        return pat.sub(lambda m: new, doc)
    i = doc.index(anchor)
    indent = doc[doc.rfind('\n', 0, i) + 1:i]
    return doc[:i] + new + '\n' + indent + doc[i:]

doc = put(doc, '  /* tutorials:start', '/* tutorials:end */\n', CSS, '  /* site-chrome:start')
doc = put(doc, '<!-- tutorials-nav:start -->', '<!-- tutorials-nav:end -->', nav,
          '<div class="group">\n      <div class="group-label">No server</div>')
doc = put(doc, '<!-- tutorials:start', '<!-- tutorials:end -->', content, '<section id="library-mode">')
if doc != before:
    open(DOCS, 'w').write(doc)
print('updated' if doc != before else 'nothing to change')
