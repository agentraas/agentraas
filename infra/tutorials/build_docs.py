def put(doc, start, end, new, anchor):
    pat = re.compile(re.escape(start) + r'.*?' + re.escape(end), re.S)
    if pat.search(doc):
        return pat.sub(lambda m: new, doc)
    i = doc.index(anchor)
    indent = doc[doc.rfind('\n', 0, i) + 1:i]
    return doc[:i] + new + '\n' + indent + doc[i:]

